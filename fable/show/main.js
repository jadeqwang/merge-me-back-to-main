const MODS = [s01, s02, s03, s04, s05, s06, s07, s08, s09, s10, s11, s12, s13, s14, s15, s16];
let K, SEQ, dev;

export async function setup(E) {
  K = await makeKit(E); dev = E.Q.get('dev');
  SEQ = MODS.map((m) => { const s = m.default || m.seq; const o = s(K); return o; });
  for (let i = 0; i < SEQ.length - 1; i++) if (Math.abs(SEQ[i].t1 - SEQ[i + 1].t0) > 1e-6) console.log(`sequence gap between ${SEQ[i].name} and ${SEQ[i + 1].name}`);
  if (dev === 'cuts') {      // the film's cuts, from the camera itself: node fable/tools/render.mjs --show /fable/show/main.js --q "dev=cuts&standin=1" --stills 0:/tmp/mfb/x.png | grep -o 'CUTS.*' | cut -c6- > fable/show/cuts.json
    dev = null; const cam = (t) => { const c = frame(t).camera, d = [c.target[0] - c.pos[0], c.target[1] - c.pos[1], c.target[2] - c.pos[2]], l = Math.hypot(...d) || 1; return { p: c.pos, d: d.map((x) => x / l) }; };
    const diff = (a, b) => [Math.hypot(a.p[0] - b.p[0], a.p[1] - b.p[1], a.p[2] - b.p[2]), Math.acos(Math.min(1, a.d[0] * b.d[0] + a.d[1] * b.d[1] + a.d[2] * b.d[2]))];
    const dt = 1 / 60, cuts = [], end = SEQ[SEQ.length - 1].t1 - 0.05, C = [], J = []; for (let t = 0; t < end; t += dt) C.push(cam(t)); for (let i = 1; i < C.length; i++) J.push(diff(C[i - 1], C[i]));
    for (let i = 1; i < J.length - 1; i++) { const [j, an] = J[i], nj = Math.max(J[i - 1][0], J[i + 1][0]), na = Math.max(J[i - 1][1], J[i + 1][1]);      // a jump far larger than the motion on either side of it
      if ((j > 0.5 && j > 6 * (nj + 0.02)) || (an > 0.10 && an > 6 * (na + 0.004))) { let lo = i * dt, hi = (i + 1) * dt; for (let k = 0; k < 9; k++) { const m = (lo + hi) / 2, d = diff(C[i], cam(m)); if (d[0] > 0.5 * j || d[1] > 0.5 * an + 1e-3) hi = m; else lo = m; } cuts.push(+hi.toFixed(3)); } }
    console.log('CUTS ' + JSON.stringify({ note: 'generated by main.js dev=cuts (camera discontinuities); the anime figure never blinks across one', cuts })); dev = 'cuts';
  }
  console.log('world: M1 x=' + K.world.M1[0].toFixed(0) + ' hero connector ' + (K.world.heroPath.roads[10].len).toFixed(0) + ' m, hero path ' + K.world.heroPath.len.toFixed(0) + ' m');
}

function devFrame(t) {
  const W = K.world;
  if (dev === 'almond') { const b = W.almondBox; if (!devFrame.p) { devFrame.p = 1; console.log('almondBox', JSON.stringify(b), 'forkBox', JSON.stringify(W.forkBox)); } const c = W.frameBox(b.x0 - 60, b.x1 + 80, b.z0, b.z1, { up: K.E.Q.get('up') || 'map' }); return { camera: c, env: { dawn: 0, ground: { fogAmt: 0, ripple: 0, base: K.hex('#0A0F46'), f0: 0.1 }, grade: K.grade(0, { vignette: 0.2, streak: 0, bloom: 0.5 }) }, drawables: W.draw(t, { minPx: 1.4, text: 0, conn: { gain: 0.6, halo: 0, minPx: 1.0 }, canopy: K.E.Q.get('plain') ? false : { gain: 0.6 }, lights: K.E.Q.get('plain') ? false : { gain: 0.5, minPx: 1.2 } }), hud: { branch: 'main', color: K.LANE.main, count: W.count(t) } }; }
  if (dev === 'map') { const c = W.frameBox(-1450, 2700, -1700, 1500, { up: 'map' }); return { camera: c, env: { dawn: 0, ground: { fogAmt: 0, ripple: 0, base: K.hex('#0A0F46'), f0: 0.1 }, grade: K.grade(0, { vignette: 0.2 }) }, drawables: W.draw(t, { head: K.E.Q.get('all') ? 1e9 : t, minPx: 1.6, text: 0, canopy: true }), hud: { branch: 'main', color: K.LANE.main, count: W.count(t) } }; }
  // dev=cast: a turntable of four performances (--q "dev=cast&dawn=0.6&a=idle&b=violet&c=float&d=build")
  K.cast.begin(); const dawn = +(K.E.Q.get('dawn') || 0); const a = t * 0.5; const q = (k, d) => K.E.Q.get(k) || d; const tk = (n) => t - K.cast.songT0(n);
  K.cast.actor('hero').set({ pos: [0, 0, 0], yaw: 0.5, track: q('a', 'idle'), time: tk(q('a', 'idle')) });
  K.cast.actor('v', { lane: 'violet', variant: 'violet' }).set({ pos: [1.6, 0, 0], yaw: -0.6, track: q('b', 'sit_idle'), time: tk(q('b', 'sit_idle')) });
  K.cast.actor('f', { lane: 'mint' }).set({ pos: [-1.8, 0, 0.5], yaw: 0, track: q('c', 'float'), time: tk(q('c', 'float')) });
  K.cast.actor('s', { lane: 'rose' }).set({ pos: [3.4, 0, 0], yaw: 0.3, track: q('d', 'life_wushu'), time: tk(q('d', 'life_wushu')) });
  return { camera: { pos: [Math.sin(a) * 7, 1.6, Math.cos(a) * 7 + 0.01], target: [0.8, 0.9, 0], fov: 35, aperture: 0.03 }, env: { dawn, grade: K.grade(dawn) }, drawables: K.cast.drawables(dawn, t), hud: null };
}

export function frame(t) {
  if (dev === 'cuts') return devFrame(0); if (dev) return devFrame(t);
  const tt = Math.min(Math.max(t, 0), SEQ[SEQ.length - 1].t1 - 1e-4);
  let s = SEQ[0]; for (const q of SEQ) if (tt >= q.t0) s = q;
  K.cast.begin();
  const F = s.frame(tt, K) || {};
  const env = F.env || {}; const dawn = env.dawn ?? K.world.dawn(tt);
  const out = { camera: F.camera, env: { ...env, dawn, grade: K.grade(dawn, env.grade || {}) }, drawables: [], type: F.type || [], hud: F.hud === undefined ? null : F.hud, overlay: F.overlay, clock: F.clock };
  if (F.world !== false) out.drawables.push(...K.world.draw(tt, F.world || {}));
  if (F.extra) out.drawables.push(...F.extra);
  out.drawables.push(...K.cast.drawables(dawn, tt, env.figLight));
  if (F.fade) { const g = out.env.grade; g.exposure = (g.exposure ?? 1) * (1 - clamp01(F.fade)); }
  if (F.flash) { const g = out.env.grade; g.exposure = (g.exposure ?? 1) * (1 + 6 * F.flash); g.bloom = (g.bloom ?? 0.5) + 1.5 * F.flash; }
  return out;
}
